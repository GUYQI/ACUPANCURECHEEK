"""Extract the chapter-11 clinical cases from the plain-text export of the book
into data/book-cases.js.  Usage: python3 tools/extract_cases.py book.txt data/book-cases.js
The case text is kept verbatim; only page-break markers and figure captions are removed."""
import sys, re, json

SRC, OUT = sys.argv[1], sys.argv[2]
lines = open(SRC, encoding='utf-8').read().split('\n')
start = next(i for i, l in enumerate(lines) if l.startswith('# פרק אחד-עשר'))
end = next(i for i, l in enumerate(lines) if l.startswith('# פרק שנים-עשר'))
page = 0
for l in lines[:start]:
    m = re.match(r'^עמוד (\d+)$', l)
    if m: page = int(m.group(1))

SECTIONS = {'א': ('holo', 'הרובד ההולוגרפי'), 'ב': ('sanjiao', 'מחלות המחמם המשולש'), 'ג': ('psych', 'מחלות גוף-נפש')}
# ordered: longer names first so that "שורש כף היד" is not also counted as "היד"
B = r'(?<![\u0590-\u05FF])ו?'   # word start, optionally with the conjunction ו
E = r'(?![\u0590-\u05FF])'
POINTS = [
    ('CA-11', r'שורש(?:-| )כף היד|פרק כף היד'), ('CA-16', r'כפות הרגליים|כף הרגל'),
    ('CA-1', B + r'הראש' + E), ('CA-2', r'המחמם העליון'), ('CA-3', r'המחמם האמצעי|המחמם התיכון'),
    ('CA-4', r'המחמם התחתון'), ('SJ', r'המחמם המשולש'),
    ('CA-5', B + r'הצוואר' + E), ('CA-6', B + r'הגב' + E), ('CA-7', B + r'המותן' + E), ('CA-8', B + r'העצה' + E),
    ('CA-9', B + r'הכתף' + E), ('CA-10', B + r'המרפק' + E), ('CA-12', B + r'היד' + E), ('CA-13', B + r'הירך' + E),
    ('CA-14', B + r'הברך' + E), ('CA-15', B + r'הקרסול' + E),
]
TREAT = re.compile(r'נבחר|נדקר|חוזק|הוספ|נוספ|בדקירה')

def detect(treatment):
    t, found = treatment, re.findall(r'CA-\d+', treatment)
    t = re.sub(r'\(CA-\d+\)', ' ', t)
    # "המחמם האמצעי והתחתון" -> name both burners explicitly
    t = re.sub(r'המחמם (העליון|האמצעי|התיכון) וה(אמצעי|תחתון)', r'המחמם \1 המחמם ה\2', t)
    t = re.sub(r'המחמם (העליון|האמצעי|התיכון) המחמם האמצעי וה(תחתון)', r'המחמם \1 המחמם האמצעי המחמם ה\2', t)
    for code, pat in POINTS:
        if re.search(pat, t):
            found += ['CA-2', 'CA-3', 'CA-4'] if code == 'SJ' else [code]
            t = re.sub(pat, ' ', t)
    return sorted(set(found), key=lambda c: int(c.split('-')[1]))

cases, cur, sec, region = [], None, None, None
for l in lines[start:end]:
    m = re.match(r'^עמוד (\d+)$', l)
    if m: page = int(m.group(1)); continue
    if l.startswith('## '):
        sec = SECTIONS[l[3]]; region = None; continue
    if l.startswith('### '):
        region = re.sub(r'^### \(\d+\)\s*', '', l); continue
    m = re.match(r'^(\d+)\. (.+?) \(איור ([\d-]+)\)$', l)
    if m and sec:
        cur = {'id': 'case-' + m.group(3), 'n': int(m.group(1)), 'title': m.group(2), 'figure': m.group(3),
               'layer': sec[0], 'layerName': sec[1], 'region': region, 'page': page, 'parts': []}
        cases.append(cur); continue
    if l.startswith('איור ') or l.startswith('#') or not cur: continue
    cur['parts'].append(l.strip())

for c in cases:
    text = ' '.join(c.pop('parts'))
    text = re.sub(r'\s+', ' ', text).strip()
    c['text'] = text
    sentences = re.split(r'(?<=[.;])\s', text)
    dx = next((s for s in sentences if 'אבחנה' in s), '')
    c['diagnosis'] = re.sub(r'^.*?אבחנה:\s*', '', dx).split('. ')[0].rstrip('.') if dx else ''
    tr = [s for s in sentences if TREAT.search(s) and 'אבחנה' not in s or re.search(r'אבחנה.*נבחר', s)]
    c['treatment'] = ' '.join(tr)
    c['points'] = detect(' '.join(re.sub(r'^.*?(נבחר)', r'\1', s) for s in tr))

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/extract_cases.py from the book (ch. 11). Do not edit by hand.\n')
    f.write('window.CA_BOOK_CASES = ' + json.dumps(cases, ensure_ascii=False, indent=1) + ';\n')
print(len(cases), 'cases')
